"""Load test for the incident intake -> analyze -> poll -> report path.

Run against a live docker-compose stack (default http://localhost:8000):

    locust -f tests/load/locustfile.py --host http://localhost:8000

or headless via scripts/run_load_test.sh. Each simulated user logs in once
as the seeded operator account (see scripts/seed_users.py /
SEED_OPERATOR_EMAIL / SEED_OPERATOR_PASSWORD) and then repeats the same
sequence a real on-call engineer would: file an incident, kick off an
analysis, poll until it settles (or a bounded number of attempts elapse),
then read the report.

Analysis runs go through the real LangGraph pipeline on the Celery worker,
including an LLM call — so this also exercises the queue/worker path, not
just the API's request-handling overhead.
"""

import os
import random

import gevent
from locust import HttpUser, between, task

OPERATOR_EMAIL = os.environ.get("LOAD_TEST_EMAIL", "operator@incidentpilot.example")
OPERATOR_PASSWORD = os.environ.get("LOAD_TEST_PASSWORD", "operator-demo-password")

SERVICES = ["checkout-api", "payments-api", "auth-service", "inventory-service"]
SEVERITIES = ["low", "medium", "high", "critical"]

MAX_POLL_ATTEMPTS = 5
POLL_WAIT_SECONDS = 2


class IncidentPilotUser(HttpUser):
    wait_time = between(1, 3)

    def on_start(self):
        response = self.client.post(
            "/auth/login",
            json={"email": OPERATOR_EMAIL, "password": OPERATOR_PASSWORD},
            name="/auth/login",
        )
        token = response.json().get("access_token") if response.status_code == 200 else None
        self.headers = {"Authorization": f"Bearer {token}"} if token else {}

    @task(3)
    def create_and_analyze_incident(self):
        create_resp = self.client.post(
            "/incidents",
            json={
                "title": f"Load-test incident {random.randint(1, 1_000_000)}",
                "severity": random.choice(SEVERITIES),
                "description": "Synthetic incident generated by the load test.",
                "service_name": random.choice(SERVICES),
            },
            headers=self.headers,
            name="/incidents [create]",
        )
        if create_resp.status_code != 201:
            return
        incident_id = create_resp.json()["id"]

        analyze_resp = self.client.post(
            f"/incidents/{incident_id}/analyze",
            headers=self.headers,
            name="/incidents/{id}/analyze",
        )
        if analyze_resp.status_code != 202:
            return
        run_id = analyze_resp.json()["analysis_run_id"]

        for _ in range(MAX_POLL_ATTEMPTS):
            status_resp = self.client.get(
                f"/incidents/{incident_id}/analyze/{run_id}",
                headers=self.headers,
                name="/incidents/{id}/analyze/{run_id} [poll]",
            )
            if status_resp.status_code != 200:
                break
            if status_resp.json().get("status") in ("completed", "failed", "awaiting_approval"):
                break
            gevent.sleep(POLL_WAIT_SECONDS)

    @task(1)
    def list_incidents(self):
        self.client.get("/incidents", headers=self.headers, name="/incidents [list]")
